#!/usr/bin/env bash
# Regenerates index.ts: one `export *` per public design-system module
# (everything under web/src/components/design-system except stories, tests,
# and internal/), plus the chart constants and the internal ChartLegend
# (it has its own stories). Run from anywhere.
set -euo pipefail
cd "$(dirname "$0")"
# Icon exports are generated and gitignored; previews need them before bundling.
pnpm --dir ../.. exec turbo run build --filter=@langfuse/icons
D=../../web/src/components/design-system
# Browser `process` shim: Next/next-auth/env.mjs read process.env at module
# scope. NEXT_PUBLIC_* values mirror what the Storybook build inlines (it runs
# under ../../.env.dev.example), so previews match the reference render.
{
  echo '// GENERATED by gen-entry.sh - do not hand-edit.'
  printf 'var env = { NODE_ENV: "development"'
  grep -E '^NEXT_PUBLIC_[A-Z0-9_]+=' ../../.env.dev.example | sed -E 's/^([A-Z0-9_]+)="?([^"]*)"?$/, \1: "\2"/' | tr -d '\n'
  echo ' };'
  echo 'if (typeof globalThis.process === "undefined") globalThis.process = { env: env, browser: true, platform: "browser", version: "", versions: {}, cwd: function () { return "/"; }, nextTick: function (f) { var a = [].slice.call(arguments, 1); Promise.resolve().then(function () { f.apply(null, a); }); } };'
  echo 'else globalThis.process.env = Object.assign({}, env, globalThis.process.env);'
} > process-shim.js
# Public assets: DS components load web/public files via
# `${env.NEXT_PUBLIC_BASE_PATH ?? ""}/<file>`. The bundle ships no loose files,
# so embed each as a data URL and remap matching <img src> values at runtime.
# copy-css.sh injects the same script into the reference iframe.html.
ASSETS="$(cd "$D" && grep -rhoE 'NEXT_PUBLIC_BASE_PATH \?\? ""\}/[A-Za-z0-9._/-]+' --include='*.tsx' --exclude='*.stories.tsx' . \
  | sed -E 's|.*\}/||' | LC_ALL=C sort -u)"
# shellcheck disable=SC2086
node - ../../web/public $ASSETS > public-assets.js <<'JS'
const fs = require("fs");
const path = require("path");
const [dir, ...files] = process.argv.slice(2);
const mime = { ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".ico": "image/x-icon" };
const assets = Object.fromEntries(files.map((f) => [
  "/" + f,
  `data:${mime[path.extname(f)] || "application/octet-stream"};base64,` + fs.readFileSync(path.join(dir, f)).toString("base64"),
]));
process.stdout.write(`// GENERATED by gen-entry.sh - do not hand-edit.
(function () {
  if (typeof window === "undefined" || window.__dsPublicAssets) return;
  var assets = ${JSON.stringify(assets)};
  window.__dsPublicAssets = assets;
  function remap(value) {
    if (typeof value !== "string") return value;
    var p = globalThis.process, base = (p && p.env && p.env.NEXT_PUBLIC_BASE_PATH) || "";
    var key = base && value.indexOf(base) === 0 ? value.slice(base.length) : value;
    return Object.prototype.hasOwnProperty.call(assets, key) ? assets[key] : value;
  }
  var setAttribute = Element.prototype.setAttribute;
  Element.prototype.setAttribute = function (name, value) {
    if (this.tagName === "IMG" && String(name).toLowerCase() === "src") value = remap(value);
    return setAttribute.call(this, name, value);
  };
  var src = Object.getOwnPropertyDescriptor(HTMLImageElement.prototype, "src");
  Object.defineProperty(HTMLImageElement.prototype, "src", {
    configurable: true, enumerable: src.enumerable, get: src.get,
    set: function (value) { src.set.call(this, remap(value)); },
  });
})();
`);
JS
{
  echo '// GENERATED by gen-entry.sh - the design-sync "package entry" for the'
  echo '// Langfuse design system (which has no dist/ build). Do not hand-edit.'
  echo 'import "./process-shim.js"; // must stay first - see gen-entry.sh'
  echo 'import "./public-assets.js";'
  (cd "$D" && find . -name '*.tsx' ! -name '*.stories.tsx' ! -name '*.test.tsx' ! -name '*.clienttest.tsx' \
    ! -path './internal/*' ! -path './charts/ChartLegend.tsx' | LC_ALL=C sort) \
    | sed 's|^\./||; s|\.tsx$||' | while read -r p; do echo "export * from \"$D/$p\";"; done
  echo "export * from \"$D/charts/constants\";"
  echo "export { ChartLegend } from \"$D/internal/charts/ChartLegend\";"
  # Shared app components (web/src/components outside design-system) that have
  # stories. Named exports, not `export *`: their modules also export helpers
  # and shadcn primitives whose names clash with DS components. Components a
  # DS component already covers are left out (see NOTES.md "Scope").
  S=../../web/src/components
  while read -r mod names; do echo "export { $names } from \"$S/$mod\";"; done <<'EOF'
CrashModal/CrashModal CrashModal
EnvLabelBadge EnvLabelBadge
GroupedScoreBadges GroupedScoreBadges
ItemBadge ItemBadge, ItemTypeIcon
MediaFileCard/MediaFileCard MediaFileCard
MediaTag/MediaTag MediaTag
OrganizationDropdownMenu/OrganizationDropdownMenu OrganizationDropdownMenu
ProjectDropdownMenu/ProjectDropdownMenu ProjectDropdownMenu
ScoreBadge/ScoreBadge ScoreBadge
ScoreTag ScoreTag, SCORE_LEVEL_LABELS
layouts/MobilePageActionsContent MobilePageActionsContent
ui/popover Popover, PopoverTrigger
nav/AppSidebar/AppSidebar AppSidebar
onboarding/components/EvaluatorsOnboardingView/EvaluatorsOnboardingView EvaluatorsOnboardingView
table/ColumnVisibilityHeader ColumnVisibilityHeader
table/data-table DataTable
table/FacetHeader FacetHeader
table/KeyValueFilterBuilder KeyValueFilterBuilder
table/OverviewSelectionBar/OverviewSelectionBar OverviewSelectionBar
table/table-view-presets/components/TableViewPresetsButton TableViewPresetsButton
ui/MarkdownViewer MarkdownView
ui/StatusBadge/StatusBadge StatusBadge
ui/AIAssistedInput AIAssistedInput
ui/drawer Drawer, DrawerController, DrawerTrigger, DrawerClose, DrawerContent, DrawerHeader, DrawerTitle, DrawerDescription
ui/sidebar SidebarProvider, SidebarInset
EOF
  echo "export { LangfuseProvider } from \"./LangfuseProvider\";"
  # Icon props (Button/IconButton `icon`, ...) take typed icon wrappers; the
  # namespace export avoids clashes with DS names like Table/Tag.
  echo "export * as LucideIcons from \"@langfuse/icons\";"
} > index.ts
