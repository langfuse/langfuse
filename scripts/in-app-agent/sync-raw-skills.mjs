#!/usr/bin/env node

import {
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { format as formatWithPrettier } from "prettier";

const repoRoot = resolve(new URL("../..", import.meta.url).pathname);
const generatedDir = resolve(
  repoRoot,
  "worker/src/features/in-app-agent/runtime/skills/generated",
);
const generatedModuleName = "skill-markdown.ts";
const sourceApiUrl =
  "https://api.github.com/repos/langfuse/skills/contents/skills/langfuse/references?ref=main";

const isCheckMode = process.argv.includes("--check");

const getGitHubHeaders = () => ({
  Accept: "application/vnd.github+json",
  Authorization: process.env.GITHUB_TOKEN
    ? `Bearer ${process.env.GITHUB_TOKEN}`
    : undefined,
  "User-Agent": "langfuse-sync-in-app-agent-raw-skills",
});

const fetchText = async (url) => {
  const response = await fetch(url, {
    headers: getGitHubHeaders(),
  });

  if (!response.ok) {
    throw new Error(
      `Failed to fetch ${url}: ${response.status} ${response.statusText}${
        !process.env.GITHUB_TOKEN &&
        (response.status === 404 || response.status === 429)
          ? ". Set GITHUB_TOKEN if the repository is private or CI is hitting GitHub API rate limits."
          : ""
      }`,
    );
  }

  return response.text();
};

const listRemoteMarkdownFiles = async () => {
  const response = await fetch(sourceApiUrl, {
    headers: getGitHubHeaders(),
  });

  if (!response.ok) {
    throw new Error(
      `Failed to list remote skills: ${response.status} ${response.statusText}${
        !process.env.GITHUB_TOKEN &&
        (response.status === 404 || response.status === 429)
          ? ". Set GITHUB_TOKEN if the repository is private or CI is hitting GitHub API rate limits."
          : ""
      }`,
    );
  }

  const entries = await response.json();

  if (!Array.isArray(entries)) {
    throw new Error(
      "Unexpected GitHub API response while listing remote skills",
    );
  }

  return entries
    .filter(
      (entry) =>
        entry.type === "file" &&
        typeof entry.name === "string" &&
        entry.name.endsWith(".md") &&
        typeof entry.download_url === "string",
    )
    .sort((left, right) => left.name.localeCompare(right.name));
};

const getExpectedFiles = async () => {
  const remoteFiles = await listRemoteMarkdownFiles();
  const expectedFiles = [];

  for (const remoteFile of remoteFiles) {
    const content = await fetchText(remoteFile.download_url);
    expectedFiles.push({ name: remoteFile.name, content });
  }

  return expectedFiles;
};

const renderGeneratedModule = async (files) => {
  // Markdown is inlined as string literals (instead of raw `.md` imports) so
  // the module compiles under plain tsc in worker without bundler support.
  const entries = files
    .map(
      ({ name, content }) =>
        `  { fileName: ${JSON.stringify(name)}, markdown: ${JSON.stringify(content)} },`,
    )
    .join("\n");

  return formatWithPrettier(
    `// This file is generated by scripts/in-app-agent/sync-raw-skills.mjs.
// Do not edit it manually.

export const LANGFUSE_IN_APP_AGENT_SKILL_MARKDOWN = [
${entries}
] as const;
`,
    { parser: "typescript" },
  );
};

const main = async () => {
  const expectedFiles = await getExpectedFiles();
  const expectedFileNames = expectedFiles.map((file) => file.name);
  const generatedModuleContent = await renderGeneratedModule(expectedFiles);

  mkdirSync(generatedDir, { recursive: true });

  if (isCheckMode) {
    const mismatches = [];

    try {
      if (
        readFileSync(resolve(generatedDir, generatedModuleName), "utf8") !==
        generatedModuleContent
      ) {
        mismatches.push(`${generatedModuleName} differs from generated output`);
      }
    } catch (error) {
      if (error.code === "ENOENT") {
        mismatches.push(`${generatedModuleName} is missing locally`);
      } else {
        throw error;
      }
    }

    if (mismatches.length > 0) {
      console.error("Generated in-app agent skills are out of sync:");
      for (const mismatch of mismatches) {
        console.error(`- ${mismatch}`);
      }
      process.exit(1);
    }

    console.log(
      `Generated in-app agent skills are in sync: ${expectedFileNames.join(", ")}`,
    );
    return;
  }

  writeFileSync(
    resolve(generatedDir, generatedModuleName),
    generatedModuleContent,
  );

  console.log(`Synced ${expectedFiles.length} generated in-app agent skills:`);
  for (const fileName of expectedFileNames) {
    console.log(`- ${fileName}`);
  }
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
