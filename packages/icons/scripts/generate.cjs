const fs = require("node:fs");
const path = require("node:path");

// Static named imports and pure wrapper calls let bundlers discard unused icons.
for (const [entrypoint, library] of [
  ["index", "lucide-react"],
  ["si", "react-icons/si"],
  ["tb", "react-icons/tb"],
]) {
  const outputDirectory = path.join(
    __dirname,
    `../dist/generated/${entrypoint}`,
  );
  fs.mkdirSync(outputDirectory, { recursive: true });
  // Remove stale icons and legacy per-icon declarations from earlier builds.
  for (const filename of fs.readdirSync(outputDirectory)) {
    if (filename.endsWith(".js") || filename.endsWith(".d.ts"))
      fs.unlinkSync(path.join(outputDirectory, filename));
  }
  const groups = new Map();
  for (const [name, icon] of Object.entries(require(library)).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    if (name === "Icon" || !/^[A-Z]/.test(name)) continue;
    if (
      typeof icon !== "function" &&
      !(icon && typeof icon === "object" && "$$typeof" in icon)
    )
      continue;
    const aliases = groups.get(icon) ?? [];
    aliases.push(name);
    groups.set(icon, aliases);
  }
  const lines = [
    "// Generated by pnpm --filter @langfuse/icons generate. Do not edit.",
  ];
  // Keep declarations together so TypeScript need not load a module per icon.
  const declarations = [
    lines[0],
    'import type { IconComponent } from "./create-icon.js";',
  ];
  for (const names of groups.values()) {
    const [name, ...aliases] = names;
    fs.writeFileSync(
      path.join(outputDirectory, `${name}.js`),
      [
        lines[0],
        'import { createIcon } from "../../create-icon.js";',
        `import { ${name} as Raw${name} } from ${JSON.stringify(library)};`,
        `export const ${name} = /* @__PURE__ */ createIcon(Raw${name}, ${JSON.stringify(name)}, ${entrypoint === "si" ? "0" : "2"});`,
        "",
      ].join("\n"),
    );
    const exports = [
      name,
      ...aliases.map((alias) => `${name} as ${alias}`),
    ].join(", ");
    lines.push(
      `export { ${exports} } from "./generated/${entrypoint}/${name}.js";`,
    );
    declarations.push(
      `declare const ${name}: IconComponent;`,
      `export { ${exports} };`,
    );
  }
  fs.writeFileSync(
    path.join(__dirname, `../dist/${entrypoint}.js`),
    lines.join("\n") + "\n",
  );
  fs.writeFileSync(
    path.join(__dirname, `../dist/${entrypoint}.d.ts`),
    [
      ...declarations,
      'export type { IconColor, IconComponent, IconProps, IconSize } from "./create-icon.js";',
      "",
    ].join("\n"),
  );
}
